# Escape Characters
print("""Algonex""")
print("Algonex', In Bangalore")
print('Algonex', 'In Bangalore')
# print('Algonex", 'In Bangalore') --> Error
print("Hello 'Kiran', welcome to the Algonex community!")
print('Hello "Kiran", welcome to the Algonex community!')

print("Hello \"Kiran\", welcome to the Algonex community!") #--> Escape Character 
print("Hello \'Kiran\", welcome 'to the Algonex community!") #--> Escape Character 
print("Hello \\""Kiran\\"", welcome to the Algonex community!") #--> Escape Character 
print("Hello \'Kiran\\, welcome to the Algonex community!") #--> Escape Character
